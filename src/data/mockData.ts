export function getPatientHistory(patientId: string): ScreeningHistoryEntry[] {
  const patient = patients.find(p => p.id === patientId);
  if (!patient) return [];
  const history: ScreeningHistoryEntry[] = [];
  const stages = patient.previousStage !== null ? [0, patient.previousStage, patient.currentStage] : [patient.currentStage];
  const dates = ['2026-03-15', '2026-06-10', '2026-09-12'];
  const confidences = [85, 88, patient.aiConfidence];
  const reviews: ScreeningHistoryEntry['doctorReview'][] = ['Confirmed', 'Confirmed', patient.doctorReview];
  const findingsList = [
    'Early signs of retinopathy detected',
    'Moderate progression observed',
    patient.currentStage >= 3 ? 'Severe abnormalities detected' : 'Stable condition',
  ];
  for (let i = 0; i < stages.length; i++) {
    history.push({
      date: dates[i] || '2026-09-12',
      stage: stages[i] as 0 | 1 | 2 | 3 | 4,
      confidence: confidences[i] || 90,
      doctorReview: reviews[i] || 'Pending',
      findings: findingsList[i] || '',
    });
  }
  return history;
}

